#!/usr/bin/env python3
"""Generate or verify THIRD_PARTY_NOTICES from the modules linked into the binary.

Uses only the Python 3 standard library. Runs `go list -deps -json .` at the
repository root, collects the deduplicated third-party modules, reads each
module's license file (plus PATENTS/NOTICE when present), and writes or
byte-compares the repository-root THIRD_PARTY_NOTICES file.

Beyond the module root, the script also collects:

- license files (LICENSE*, COPYING, NOTICE*, PATENTS) in the directories
  between each linked package and its module root, e.g. a package that
  carries its own LICENSE in a subdirectory;
- license notices in the headers of compiled source files, either
  `SPDX-License-Identifier: <id>` or the Apache-2.0 boilerplate line
  `Licensed under the Apache License, Version 2.0`. A header license that
  differs from the module's root license adds a "Portions" section with the
  affected packages, the deduplicated copyright lines, and the license text
  from scripts/licenses/<id>.txt.

Modes:
  --write   write THIRD_PARTY_NOTICES
  --check   compare against the existing file; exit 1 with a diff on mismatch
"""

import argparse
import difflib
import fnmatch
import json
from pathlib import Path
import re
import subprocess
import sys

LICENSE_NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING", "LICENCE")
EXTRA_NAMES = ("PATENTS", "NOTICE")
COMPILED_LISTS = ("GoFiles", "CgoFiles", "CFiles", "CXXFiles", "MFiles",
                  "HFiles", "FFiles", "SFiles", "SwigFiles", "SwigCXXFiles")
SEPARATOR = "=" * 80
SUBSEPARATOR = "-" * 80

HEADER = """\
THIRD-PARTY SOFTWARE NOTICES

This file is generated by scripts/third-party-notices.py from the output of
`go list -deps -json .` run at the repository root. It contains the license
texts of every third-party Go module linked into the Branchline binary.

Do not edit by hand. After changing dependencies, regenerate with:

    python3 scripts/third-party-notices.py --write

and verify with:

    python3 scripts/third-party-notices.py --check
"""

PACKAGE_RE = re.compile(r"(?m)^package\s")
SPDX_RE = re.compile(r"SPDX-License-Identifier:\s*(\S.*)")
APACHE_HEADER_RE = re.compile(r"Licensed under the Apache License, Version 2\.0")
LICENSED_UNDER_RE = re.compile(r"licensed under", re.IGNORECASE)
COPYRIGHT_RE = re.compile(r"(?m)^\s*(?://+\s?|/\*+\s?|\*\s?)?(Copyright\b[^\n]*)")


class NoticesError(Exception):
    """A license problem that must fail --write and --check."""


def fail(message):
    raise NoticesError(message)


def stream_json_objects(data):
    """Parse a stream of concatenated JSON objects into dicts."""
    decoder = json.JSONDecoder()
    index = 0
    length = len(data)
    while index < length:
        while index < length and data[index] in " \t\r\n":
            index += 1
        if index >= length:
            break
        obj, end = decoder.raw_decode(data, index)
        yield obj
        index = end


def collect_modules(repo_root):
    """Run `go list -deps -json .` and return the third-party modules.

    Each entry has the module version, the module directory, and the linked
    packages of that module with their directories and compiled file names.
    """
    try:
        result = subprocess.run(
            ["go", "list", "-deps", "-json", "."],
            cwd=repo_root, capture_output=True, text=True, timeout=300,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        fail(f"failed to run `go list -deps -json .`: {exc}")
    if result.returncode != 0:
        fail("`go list -deps -json .` exited "
             f"{result.returncode}: {result.stderr.strip()}")

    modules = {}
    for package in stream_json_objects(result.stdout):
        module = package.get("Module")
        if not module or module.get("Main"):
            continue
        replace = module.get("Replace")
        path = module.get("Path", "")
        version = module.get("Version", "")
        if replace and replace.get("Version"):
            path = replace.get("Path", path)
            version = replace.get("Version", version)
        directory = module.get("Dir", "")
        if replace and replace.get("Dir"):
            directory = replace["Dir"]
        entry = modules.setdefault(
            path, {"version": version, "dir": directory, "packages": {}})
        files = []
        for key in COMPILED_LISTS:
            files.extend(package.get(key) or [])
        entry["packages"][package.get("ImportPath", "")] = {
            "dir": package.get("Dir", ""),
            "files": files,
        }
    if not modules:
        fail("no third-party modules found in `go list -deps -json .` output")
    return modules


def detect_license(text):
    spdx = re.search(r"^SPDX-License-Identifier:\s*(\S.*)$", text, re.MULTILINE)
    if spdx:
        return spdx.group(1).strip()
    if "Apache License" in text and "Version 2.0" in text:
        return "Apache-2.0"
    if "This is free and unencumbered software released into the public domain" in text:
        return "Unlicense"
    if "Permission to use, copy, modify, and/or distribute this software" in text:
        return "ISC"
    if "Redistribution and use in source and binary forms" in text:
        if re.search(r"Neither the name|Neither the names", text):
            return "BSD-3-Clause"
        return "BSD-2-Clause"
    if "MIT License" in text or "Permission is hereby granted, free of charge" in text:
        return "MIT"
    return None


def is_licenseish_name(name):
    """Whether a file name is a license-related file worth collecting."""
    return (name in ("COPYING", "PATENTS")
            or fnmatch.fnmatchcase(name, "LICENSE*")
            or fnmatch.fnmatchcase(name, "NOTICE*"))


def find_nested_license_files(module_root, package_dirs):
    """License files between the linked packages and their module root.

    Walks from each package directory up to (but excluding) the module root
    and collects LICENSE*, COPYING, NOTICE* and PATENTS files. Returns a
    sorted list of (relative path, absolute path) deduplicated by relative
    path. Directories of packages that are not linked in are never visited.
    """
    module_root = Path(module_root).resolve()
    found = {}
    for package_dir in package_dirs:
        if not package_dir:
            fail(f"module root {module_root}: linked package has no directory")
        current = Path(package_dir).resolve()
        if not current.is_relative_to(module_root):
            fail(f"package directory {current} is not inside "
                 f"its module root {module_root}")
        while current != module_root:
            if current.parent == current:
                break
            try:
                entries = sorted(current.iterdir())
            except OSError:
                entries = []
            for entry in entries:
                if entry.is_file() and is_licenseish_name(entry.name):
                    relative = entry.relative_to(module_root).as_posix()
                    found.setdefault(relative, entry)
            current = current.parent
    return sorted(found.items())


def header_text(text):
    """The part of a source file that may carry a license header.

    For Go files this is everything before the `package` clause, so license
    words inside the code or its documentation are never mistaken for a
    header. Files without a package clause (assembly, C, headers) only
    contribute their leading comments: `//` lines and `/* ... */` blocks,
    with blank lines between them.
    """
    match = PACKAGE_RE.search(text)
    if match:
        return text[:match.start()]
    index = 0
    length = len(text)
    while index < length:
        while index < length and text[index] in " \t\r\n":
            index += 1
        if text.startswith("//", index):
            end = text.find("\n", index)
            index = length if end < 0 else end + 1
        elif text.startswith("/*", index):
            end = text.find("*/", index + 2)
            index = length if end < 0 else end + 2
        else:
            break
    return text[:index]


def scan_file_header(text):
    """Recognize the license declared in one source file's header.

    Returns a dict with the recognized license ids, the copyright lines
    (comment markers stripped), and whether the header declares a license
    in a way this script does not recognize.
    """
    header = header_text(text)
    licenses = set()
    for match in SPDX_RE.finditer(header):
        license_id = match.group(1).strip()
        if license_id.endswith("*/"):
            license_id = license_id[:-2].rstrip()
        licenses.add(license_id)
    if APACHE_HEADER_RE.search(header):
        licenses.add("Apache-2.0")
    unrecognized = bool(LICENSED_UNDER_RE.search(header)) and not licenses
    copyrights = []
    for match in COPYRIGHT_RE.finditer(header):
        copyrights.append(match.group(1).rstrip())
    return {
        "licenses": sorted(licenses),
        "copyrights": copyrights,
        "unrecognized": unrecognized,
    }


def scan_package_files(package_dir, file_names, label=None):
    """Scan the compiled files of one package for license headers.

    Test files are skipped even when they appear in the list. Returns a list
    of (file name, scan result) for files whose header declares or mentions
    a license in a way that matters. A listed file that cannot be read
    raises NoticesError; `label` names the module and package in that error.
    """
    results = []
    for name in sorted(file_names):
        if name.endswith("_test.go"):
            continue
        path = Path(package_dir) / name
        try:
            text = path.read_bytes().decode("utf-8", errors="replace")
        except OSError as exc:
            fail(f"{label or package_dir}: file {name}: "
                 f"cannot read compiled source file: {exc}")
        scan = scan_file_header(text)
        if scan["licenses"] or scan["unrecognized"]:
            results.append((name, scan))
    return results


def collect_portions(module_path, root_license_id, packages, licenses_dir):
    """Group header-declared licenses that differ from the root license.

    `packages` maps import paths to {"dir", "files"}. Returns a dict mapping
    license ids to {"packages", "copyrights", "files"}, sorted for output.
    Raises NoticesError when a header declares a license this script does
    not recognize, or when scripts/licenses/ has no text for a license that
    needs a Portions section.
    """
    portions = {}
    for import_path in sorted(packages):
        info = packages[import_path]
        label = f"module {module_path}: package {import_path}"
        for name, scan in scan_package_files(info["dir"], info["files"], label):
            if scan["unrecognized"]:
                fail(f"module {module_path}: package {import_path}: "
                     f"file {name}: license header not recognized")
            for license_id in scan["licenses"]:
                if license_id == root_license_id:
                    continue
                portion = portions.setdefault(license_id, {
                    "packages": set(), "copyrights": set(), "files": []})
                portion["packages"].add(import_path)
                portion["copyrights"].update(scan["copyrights"])
                portion["files"].append(f"{import_path}/{name}")
    for license_id in sorted(portions):
        text_file = Path(licenses_dir) / f"{license_id}.txt"
        if not text_file.is_file():
            portion = portions[license_id]
            fail(f"module {module_path}: no license text for {license_id} "
                 f"(add scripts/licenses/{license_id}.txt); "
                 f"declared in {', '.join(sorted(portion['files']))}")
    return portions


def module_entry(path, info, licenses_dir):
    directory = Path(info["dir"]) if info["dir"] else None
    if directory is None or not directory.is_dir():
        fail(f"module {path}: no readable module directory ({info['dir']!r})")

    license_text = None
    for name in LICENSE_NAMES:
        candidate = directory / name
        if candidate.is_file():
            license_text = candidate.read_bytes().decode("utf-8")
            break
    if license_text is None:
        fail(f"module {path}: no license file "
             f"({'/'.join(LICENSE_NAMES)}) in {directory}")

    license_id = detect_license(license_text)
    if license_id is None:
        fail(f"module {path}: unrecognized license text in {directory}")

    parts = []
    for extra in EXTRA_NAMES:
        candidate = directory / extra
        if candidate.is_file():
            parts.append((extra, candidate.read_bytes().decode("utf-8")))

    nested = find_nested_license_files(
        directory, [pkg["dir"] for pkg in info["packages"].values()])
    portions = collect_portions(path, license_id, info["packages"], licenses_dir)

    lines = [SEPARATOR, f"{path} {info['version']} ({license_id})", SEPARATOR, ""]
    lines.append(license_text.rstrip("\n"))
    lines.append("")
    for name, text in parts:
        lines.append(SUBSEPARATOR)
        lines.append(name)
        lines.append(SUBSEPARATOR)
        lines.append("")
        lines.append(text.rstrip("\n"))
        lines.append("")
    for relative, nested_file in nested:
        lines.append(SUBSEPARATOR)
        lines.append(relative)
        lines.append(SUBSEPARATOR)
        lines.append("")
        lines.append(nested_file.read_bytes().decode("utf-8").rstrip("\n"))
        lines.append("")
    for portion_id in sorted(portions):
        portion = portions[portion_id]
        text_file = Path(licenses_dir) / f"{portion_id}.txt"
        portion_text = text_file.read_bytes().decode("utf-8")
        lines.append(SUBSEPARATOR)
        lines.append(f"Portions licensed under {portion_id}")
        lines.append(SUBSEPARATOR)
        lines.append("")
        lines.append("Packages:")
        lines.append("")
        for import_path in sorted(portion["packages"]):
            lines.append(f"    {import_path}")
        lines.append("")
        lines.append("Copyright notices:")
        lines.append("")
        for copyright_line in sorted(portion["copyrights"]):
            lines.append(f"    {copyright_line}")
        lines.append("")
        lines.append(portion_text.rstrip("\n"))
        lines.append("")
    return "\n".join(lines)


def generate(repo_root):
    licenses_dir = Path(__file__).resolve().parent / "licenses"
    modules = collect_modules(repo_root)
    entries = []
    for path in sorted(modules):
        entries.append(module_entry(path, modules[path], licenses_dir))
    return HEADER + "\n" + "\n".join(entries), modules


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write THIRD_PARTY_NOTICES")
    mode.add_argument("--check", action="store_true", help="verify THIRD_PARTY_NOTICES is up to date")
    arguments = parser.parse_args()

    script_dir = Path(__file__).resolve().parent
    repo_root = script_dir.parent
    target = repo_root / "THIRD_PARTY_NOTICES"

    try:
        content, modules = generate(repo_root)
    except NoticesError as error:
        print(f"third-party-notices: {error}", file=sys.stderr)
        return 1
    content_bytes = content.encode("utf-8")

    if arguments.write:
        target.write_bytes(content_bytes)
        print(f"third-party-notices: wrote {target} "
              f"({len(modules)} modules: {', '.join(sorted(modules))})")
        return 0

    if not target.is_file():
        print(f"third-party-notices: {target} does not exist; "
              "run `python3 scripts/third-party-notices.py --write`", file=sys.stderr)
        return 1
    existing = target.read_bytes()
    if existing == content_bytes:
        print(f"third-party-notices: THIRD_PARTY_NOTICES is up to date "
              f"({len(modules)} modules: {', '.join(sorted(modules))})")
        return 0

    print("third-party-notices: THIRD_PARTY_NOTICES is out of date; "
          "run `python3 scripts/third-party-notices.py --write`", file=sys.stderr)
    old_lines = existing.decode("utf-8", errors="replace").splitlines(keepends=True)
    new_lines = content.splitlines(keepends=True)
    diff = list(difflib.unified_diff(old_lines, new_lines,
                                     fromfile="THIRD_PARTY_NOTICES (existing)",
                                     tofile="THIRD_PARTY_NOTICES (expected)", n=3))
    for line in diff[:120]:
        sys.stderr.write(line if line.endswith("\n") else line + "\n")
    if len(diff) > 120:
        sys.stderr.write(f"... ({len(diff) - 120} more diff lines)\n")
    return 1


if __name__ == "__main__":
    sys.exit(main())
